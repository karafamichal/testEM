"""Draws the Plan&Ride icon (logo 03: white "P", mint "&", white "R" on ink) for every surface.

Run from the project root:  python tools/make_icons.py
Needs fontTools and Pillow. The glyphs come from the app's own Barlow Semi Condensed Bold.
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "app/src/main/res/font/barlow_sc_bold.ttf"
INK, WHITE, MINT = "#14181D", "#FFFFFF", "#6EE7A8"
PARTS = [("P", WHITE), ("&", MINT), ("R", WHITE)]


def vector_paths(box: float, width: float):
    """SVG path data for P, & and R, scaled to `width` and centred in a `box`×`box` square (y down)."""
    font = TTFont(FONT)
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    upm = font["head"].unitsPerEm
    cap = font["OS/2"].sCapHeight or upm * 0.7
    names = [cmap[ord(ch)] for ch, _ in PARTS]
    total = sum(glyphs[n].width for n in names)
    s = width / total
    x = (box - width) / 2
    baseline = box / 2 + cap * s / 2
    out = []
    for (ch, color), name in zip(PARTS, names):
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(pen, (s, 0, 0, -s, x, baseline)))
        out.append((pen.getCommands(), color))
        x += glyphs[name].width * s
    return out


def android_vector(path: Path, mono: bool = False):
    # Adaptive icons are 108dp; the glyphs stay inside the 66dp safe circle.
    body = "\n".join(
        f'    <path android:fillColor="{WHITE if mono else c}" android:pathData="{d}"/>'
        for d, c in vector_paths(108, 58)
    )
    path.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icons.py -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
        f"{body}\n</vector>\n",
        encoding="utf-8",
    )


def raster(size: int, round_: bool = False, glyph_share: float = 0.62) -> Image.Image:
    """A square (or round) icon at `size` px, drawn from the same font."""
    scale = 4  # draw big, then shrink for smooth edges
    big = size * scale
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if round_:
        d.ellipse((0, 0, big - 1, big - 1), fill=INK)
    else:
        d.rectangle((0, 0, big, big), fill=INK)
    target = big * glyph_share
    font_size = big
    font = ImageFont.truetype(str(FONT), font_size)
    width = sum(d.textlength(ch, font=font) for ch, _ in PARTS)
    font = ImageFont.truetype(str(FONT), int(font_size * target / width))
    width = sum(d.textlength(ch, font=font) for ch, _ in PARTS)
    top, bottom = d.textbbox((0, 0), "P", font=font)[1::2]
    x, y = (big - width) / 2, (big - (bottom - top)) / 2 - top
    for ch, color in PARTS:
        d.text((x, y), ch, font=font, fill=color)
        x += d.textlength(ch, font=font)
    return img.resize((size, size), Image.LANCZOS)


def android_module(res: Path):
    (res / "drawable").mkdir(exist_ok=True)
    android_vector(res / "drawable/ic_launcher_foreground.xml")
    android_vector(res / "drawable/ic_launcher_monochrome.xml", mono=True)
    (res / "drawable/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Plan&amp;Ride: the P&amp;R plate sits on ink -->\n'
        '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n'
        f'    <solid android:color="{INK}" />\n</shape>\n',
        encoding="utf-8",
    )
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
        "    <!-- Themed icons (Android 13+) tint the glyphs by their shape -->\n"
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
        "</adaptive-icon>\n"
    )
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (res / "mipmap-anydpi-v26" / name).write_text(adaptive, encoding="utf-8")
    # Pre-Android 8 launchers use the bitmaps.
    for density, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        folder = res / f"mipmap-{density}"
        raster(px).save(folder / "ic_launcher.webp", "WEBP", lossless=True)
        raster(px, round_=True).save(folder / "ic_launcher_round.webp", "WEBP", lossless=True)
        (folder / "ic_launcher_foreground.webp").unlink(missing_ok=True)


if __name__ == "__main__":
    android_module(ROOT / "app/src/main/res")
    android_module(ROOT / "wear/src/main/res")
    icons = ROOT / "web/public/icons"
    raster(192).save(icons / "icon-192.png")
    raster(512).save(icons / "icon-512.png")
    raster(180).save(icons / "apple-touch-icon.png")
    raster(192).save(ROOT / "hub/static/mark.png")
    store = ROOT / "store"
    store.mkdir(exist_ok=True)
    raster(512, glyph_share=0.66).convert("RGB").save(store / "play-icon-512.png")
    print("icons written")
