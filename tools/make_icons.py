"""Draws the Plan&Ride icon for every surface: the original logo (pin, winding route, bus front) in the Zastávka
colours, blue pin and route and a slate bus on white ("option A", 2.15.1).

Run from the project root:  python tools/make_icons.py
Needs Pillow. The shapes below are the logo's, in a 240 x 200 box (the same as the design canvas).
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
TILE, BLUE, SLATE, HOLE = "#FFFFFF", "#1D4FB8", "#1F2935", "#FFFFFF"

# The logo, part by part, in the 240 x 200 box.
PIN = "M62 38a28 28 0 0 1 28 28c0 21-28 48-28 48S34 87 34 66a28 28 0 0 1 28-28z"
ROUTE = "M104 102H120a15 15 0 0 1 0 30H88a15 15 0 0 0 0 30H158"
BODY = "M138 62a16 16 0 0 1 16-16h35a16 16 0 0 1 16 16v47a6 6 0 0 1-6 6h-55a6 6 0 0 1-6-6z"
RECTS_BUS = [(127, 72, 7, 18, 3), (209, 72, 7, 18, 3), (144, 113, 12, 10, 3), (187, 113, 12, 10, 3)]  # mirrors, wheels
RECTS_GLASS = [(154, 54, 35, 6, 3), (145, 68, 53, 28, 4)]  # roof light, windscreen
LIGHTS = [(152, 105, 5), (191, 105, 5)]
NODES = [(96, 102, 8), (166, 162, 8)]
BOX = (34, 38, 216, 170)  # what the logo covers


def rect_path(x, y, w, h, r):
    return f"M{x + r} {y}h{w - 2 * r}a{r} {r} 0 0 1 {r} {r}v{h - 2 * r}a{r} {r} 0 0 1 -{r} {r}h-{w - 2 * r}a{r} {r} 0 0 1 -{r} -{r}v-{h - 2 * r}a{r} {r} 0 0 1 {r} -{r}z"


def circle_path(cx, cy, r):
    return f"M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 -{2 * r} 0z"


def android_vector(path: Path, mono: bool = False):
    """The adaptive icon's foreground (108 dp, the logo inside the 66 dp safe circle)."""
    s = 62 / (BOX[2] - BOX[0])
    tx = 54 - (BOX[0] + BOX[2]) / 2 * s
    ty = 54 - (BOX[1] + BOX[3]) / 2 * s
    c = lambda colour: "#FFFFFF" if mono else colour  # noqa: E731 - themed icons tint one colour
    parts = [f'<path android:fillColor="{c(BLUE)}" android:pathData="{PIN}"/>',
             f'<path android:strokeColor="{c(BLUE)}" android:strokeWidth="8" android:strokeLineCap="round" '
             f'android:strokeLineJoin="round" android:pathData="{ROUTE}"/>',
             f'<path android:fillColor="{c(SLATE)}" android:pathData="{BODY}"/>']
    parts += [f'<path android:fillColor="{c(SLATE)}" android:pathData="{rect_path(*r)}"/>' for r in RECTS_BUS]
    if not mono:  # holes and glass would vanish in a one-colour icon anyway
        parts.append(f'<path android:fillColor="{HOLE}" android:pathData="{circle_path(62, 66, 12)}"/>')
        parts += [f'<path android:fillColor="{HOLE}" android:pathData="{rect_path(*r)}"/>' for r in RECTS_GLASS]
        parts += [f'<path android:fillColor="{HOLE}" android:pathData="{circle_path(*l)}"/>' for l in LIGHTS]
    parts += [f'<path android:fillColor="{c(HOLE)}" android:strokeColor="{c(BLUE)}" android:strokeWidth="7" '
              f'android:pathData="{circle_path(*n)}"/>' for n in NODES]
    body = "\n        ".join(parts)
    path.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icons.py -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
        f'    <group android:translateX="{tx:.3f}" android:translateY="{ty:.3f}" android:scaleX="{s:.5f}" android:scaleY="{s:.5f}">\n'
        f"        {body}\n    </group>\n</vector>\n",
        encoding="utf-8",
    )


def draw_logo(d: ImageDraw.ImageDraw, s: float, tx: float, ty: float):
    """The logo with Pillow's shapes, scaled by s and moved by (tx, ty)."""
    P = lambda x, y: (tx + x * s, ty + y * s)  # noqa: E731
    box = lambda x0, y0, x1, y1: [*P(x0, y0), *P(x1, y1)]  # noqa: E731
    # pin: a circle and the point below it
    d.ellipse(box(34, 38, 90, 94), fill=BLUE)
    d.polygon([P(36, 76), P(88, 76), P(62, 114)], fill=BLUE)
    d.ellipse(box(50, 54, 74, 78), fill=HOLE)
    # route: one smooth line (straight runs joined by half-circles), with round ends
    import math
    w = max(1, round(8 * s))
    pts = [(104, 102), (120, 102)]
    pts += [(120 + 15 * math.cos(a), 117 + 15 * math.sin(a)) for a in [-math.pi / 2 + math.pi * i / 24 for i in range(25)]]
    pts += [(88, 132)]
    pts += [(88 - 15 * math.cos(a), 147 + 15 * math.sin(a)) for a in [-math.pi / 2 + math.pi * i / 24 for i in range(25)]]
    pts += [(158, 162)]
    d.line([P(x, y) for x, y in pts], fill=BLUE, width=w, joint="curve")
    for x, y in (pts[0], pts[-1]):
        d.ellipse(box(x - 4, y - 4, x + 4, y + 4), fill=BLUE)
    for cx, cy, r in NODES:
        d.ellipse(box(cx - r - 3.5, cy - r - 3.5, cx + r + 3.5, cy + r + 3.5), fill=BLUE)
        d.ellipse(box(cx - r + 3.5, cy - r + 3.5, cx + r - 3.5, cy + r - 3.5), fill=HOLE)
    # bus: body (round top, nearly square bottom), mirrors, wheels, glass, lights
    d.rounded_rectangle(box(138, 46, 205, 115), radius=16 * s, fill=SLATE)
    d.rounded_rectangle(box(138, 80, 205, 115), radius=6 * s, fill=SLATE)
    for x, y, rw, rh, r in RECTS_BUS:
        d.rounded_rectangle(box(x, y, x + rw, y + rh), radius=r * s, fill=SLATE)
    for x, y, rw, rh, r in RECTS_GLASS:
        d.rounded_rectangle(box(x, y, x + rw, y + rh), radius=r * s, fill=HOLE)
    for cx, cy, r in LIGHTS:
        d.ellipse(box(cx - r, cy - r, cx + r, cy + r), fill=HOLE)


def raster(size: int, round_: bool = False, share: float = 0.72) -> Image.Image:
    """A square (or round) icon at `size` px: the logo on its white tile."""
    scale = 4  # draw big, then shrink for smooth edges
    big = size * scale
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if round_:
        d.ellipse((0, 0, big - 1, big - 1), fill=TILE)
    else:
        d.rectangle((0, 0, big, big), fill=TILE)
    s = big * share / (BOX[2] - BOX[0])
    draw_logo(d, s, big / 2 - (BOX[0] + BOX[2]) / 2 * s, big / 2 - (BOX[1] + BOX[3]) / 2 * s)
    return img.resize((size, size), Image.LANCZOS)


def android_module(res: Path):
    (res / "drawable").mkdir(exist_ok=True)
    android_vector(res / "drawable/ic_launcher_foreground.xml")
    android_vector(res / "drawable/ic_launcher_monochrome.xml", mono=True)
    (res / "drawable/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Plan&amp;Ride: the logo sits on white -->\n'
        '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n'
        f'    <solid android:color="{TILE}" />\n</shape>\n',
        encoding="utf-8",
    )
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
        "    <!-- Themed icons (Android 13+) tint the logo by its shape -->\n"
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
        "</adaptive-icon>\n"
    )
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (res / "mipmap-anydpi-v26" / name).write_text(adaptive, encoding="utf-8")
    # Pre-Android 8 launchers use the bitmaps.
    for density, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        folder = res / f"mipmap-{density}"
        raster(px).save(folder / "ic_launcher.webp", "WEBP", lossless=True)
        raster(px, round_=True, share=0.62).save(folder / "ic_launcher_round.webp", "WEBP", lossless=True)


if __name__ == "__main__":
    android_module(ROOT / "app/src/main/res")
    android_module(ROOT / "wear/src/main/res")
    icons = ROOT / "web/public/icons"
    raster(192).save(icons / "icon-192.png")
    raster(512, share=0.6).save(icons / "icon-512.png")  # also the maskable one: keep the logo in the safe circle
    raster(180).save(icons / "apple-touch-icon.png")
    raster(192).save(ROOT / "hub/static/mark.png")
    store = ROOT / "store"
    store.mkdir(exist_ok=True)
    raster(512, share=0.7).convert("RGB").save(store / "play-icon-512.png")
    print("icons written")
